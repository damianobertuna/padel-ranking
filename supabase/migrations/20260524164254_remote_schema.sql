CREATE OR REPLACE VIEW "public"."view_player_stats" AS
 WITH "player_match_aggregates" AS (
         SELECT "p"."id",
            "p"."first_name",
            "p"."last_name",
            "p"."ranking",
            "p"."preferred_side",
            "p"."gender",
            "p"."avatar_url",
            COALESCE(( SELECT "count"(*) AS "count"
                   FROM "public"."matches" "m"
                  WHERE (("m"."status" = 'completed'::"text") AND (((("p"."id" = "m"."team_a_left_id") OR ("p"."id" = "m"."team_a_right_id")) OR ("p"."id" = "m"."team_b_left_id")) OR ("p"."id" = "m"."team_b_right_id")))), (0)::bigint) AS "total_played",
            COALESCE(( SELECT "count"(*) AS "count"
                   FROM "public"."matches" "m"
                  WHERE (("m"."status" = 'completed'::"text") AND (((("p"."id" = "m"."team_a_left_id") OR ("p"."id" = "m"."team_a_right_id")) AND ("m"."winning_team" = 'A'::"text")) OR ((("p"."id" = "m"."team_b_left_id") OR ("p"."id" = "m"."team_b_right_id")) AND ("m"."winning_team" = 'B'::"text"))))), (0)::bigint) AS "matches_won"
           FROM "public"."players" "p"
        )
 SELECT "id",
    "first_name",
    "last_name",
    "ranking",
    "preferred_side",
    "gender",
    "avatar_url",
    "total_played",
        CASE
            WHEN ("total_played" = 0) THEN 0.0
            ELSE "round"(((("matches_won")::numeric / ("total_played")::numeric) * (100)::numeric), 1)
        END AS "win_rate"
   FROM "player_match_aggregates";


