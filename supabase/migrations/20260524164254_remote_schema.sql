CREATE OR REPLACE FUNCTION "public"."apply_inactivity_penalties"() RETURNS "void"
    LANGUAGE "plpgsql"
    AS $$
DECLARE
  player_record RECORD;
  latest_match_date TIMESTAMPTZ;
  days_inactive INTEGER;
BEGIN
  -- Cicliamo su tutti i giocatori
  FOR player_record IN SELECT * FROM players LOOP
    
    -- Troviamo l'ultima partita completata a cui ha partecipato il giocatore
    SELECT MAX(created_at) INTO latest_match_date
    FROM matches
    WHERE status = 'completed' 
      AND (team_a_left_id = player_record.id 
           OR team_a_right_id = player_record.id 
           OR team_b_left_id = player_record.id 
           OR team_b_right_id = player_record.id);

    -- Se non ha mai giocato una partita completata, usiamo la data in cui è stato creato il suo profilo
    IF latest_match_date IS NULL THEN
      latest_match_date := player_record.created_at;
    END IF;

    -- Calcoliamo i giorni di inattività rispetto ad oggi
    days_inactive := CURRENT_DATE - latest_match_date::date;

    -- Se sono passati 60 giorni (2 mesi) o più, decurtiamo 0.10 dal ranking
    IF days_inactive >= 60 THEN
      UPDATE players 
      SET ranking = ranking - 0.10 
      WHERE id = player_record.id;
    END IF;

  END LOOP;
END;
$$;


